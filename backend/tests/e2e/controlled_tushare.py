class ControlledTushare:
    def __init__(self) -> None:
        self.requests: list[tuple[str, dict[str, object], tuple[str, ...]]] = []

    def handle(self, request: httpx.Request) -> httpx.Response:
        assert request.method == "POST", "unexpected Tushare HTTP method"
        assert str(request.url) == TUSHARE_ENDPOINT, "unexpected Tushare endpoint"
        payload: dict[str, Any] = json.loads(request.content)
        assert set(payload) == {"api_name", "token", "params", "fields"}
        api_name = str(payload["api_name"])
        assert payload["token"] == TEST_TOKEN, "unexpected test token"
        assert api_name in EXPECTED_FIELDS_BY_API, f"unexpected Tushare api: {api_name}"

        fields = tuple(str(payload["fields"]).split(","))
        assert fields == EXPECTED_FIELDS_BY_API[api_name], (
            f"unexpected fields for {api_name}"
        )

        params = payload["params"]
        assert isinstance(params, dict), "Tushare params must be an object"
        expected_params = EXPECTED_BASE_PARAMS_BY_API[api_name]
        assert set(params) == {*expected_params, "limit", "offset"}, (
            f"unexpected parameter keys for {api_name}"
        )
        assert all(params[key] == value for key, value in expected_params.items()), (
            f"unexpected parameter values for {api_name}"
        )
        assert params["limit"] == "2", f"unexpected page limit for {api_name}"
        limit = int(params["limit"])
        offset = int(params["offset"])
        assert offset >= 0 and offset % limit == 0, (
            f"unexpected page offset for {api_name}"
        )
        self.requests.append((api_name, dict(params), fields))
        all_rows = ROWS_BY_API[api_name]
        for row in all_rows:
            missing = [field for field in fields if field not in row]
            assert not missing, (
                f"fixed row for {api_name} missing requested fields: {missing}"
            )
        rows = all_rows[offset : offset + limit]

        return httpx.Response(
            200,
            json={
                "code": 0,
                "msg": "",
                "data": {
                    "fields": list(fields),
                    "items": [[row[field] for field in fields] for row in rows],
                },
            },
        )
